"""Reproduce numerical programs and arithmetic graphs using only the standard library.

Rebuilding checks byte identities. It never assigns mathematical review status.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

# Keep imports from writing cache files into an installed package's data folder.
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from compile_register import allocate_registers, compile_source
from compile_register_calls import compile_source_calls
from representation_compiler import canonical, compile_program, digest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True, help='Directory for newly generated artifacts')
    args = parser.parse_args()
    reference = json.loads((HERE / 'manifest.json').read_text(encoding='utf-8'))
    mismatches = [name for name, expected in reference['files_sha256'].items()
                  if hashlib.sha256((HERE / name).read_bytes()).hexdigest() != expected]
    if mismatches:
        raise SystemExit('Source/reference file hash mismatch: ' + ', '.join(mismatches))
    arithmetic = (HERE / 'arithmetization_programs.py').read_text(encoding='utf-8')
    pa_source = arithmetic + '\n' + (HERE / 'pa_proof_programs.py').read_text(encoding='utf-8')
    programs = {
        'substitution': allocate_registers(compile_source(arithmetic, 'substitute_closed',
                                                        'goedel-dag-closed-substitution-v1')),
        'pa_proof': compile_source_calls(pa_source, 'check_pa_proof', 'goedel-pa-hilbert-proof-v1'),
    }
    args.output.mkdir(parents=True, exist_ok=True)
    results = {}
    for name, program in programs.items():
        graph = compile_program(program)
        observed = {'program_sha256': digest(program), 'bounded_sha256': graph['bounded_sha256'],
                    'arithmetic_sha256': graph['arithmetic_sha256']}
        expected = reference['artifacts'][name]
        matches = observed == expected
        artifact = {'schema_version': '1.0', 'program': program, 'representation': graph,
                    'review_status': 'UNREVIEWED_REBUILD', 'formal_kernel': False}
        (args.output / (name + '_representation.json')).write_bytes(canonical(artifact) + b'\n')
        results[name] = {'reference_hashes_match': matches, **observed,
                         'arithmetic_dag_nodes': len(graph['arithmetic_dag']['nodes'])}
    report = {'schema_version': '1.0', 'source_hashes_match': True, 'artifacts': results,
              'review_status': 'UNREVIEWED_REBUILD', 'formal_kernel': False,
              'meaning': 'Exact source/program/formula reproduction only; archived mathematical reviews are separate.'}
    (args.output / 'build_report.json').write_bytes(canonical(report) + b'\n')
    print(json.dumps(report, indent=2))
    if not all(item['reference_hashes_match'] for item in results.values()):
        raise SystemExit('Generated byte identities differ from the versioned reference')


if __name__ == '__main__':
    main()
