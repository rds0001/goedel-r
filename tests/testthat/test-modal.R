test_that("finite modal truth and frame countermodels match hand calculations", {
  p<-modal_atom("p");m<-kripke_model(c("a","b"),list(list("a","b")),list(p=list("b")))
  expect_identical(evaluate_modal(modal_box(p),m,"a")$status,"ESTABLISHED")
  expect_identical(evaluate_modal(modal_diamond(p),m,"b")$status,"REFUTED")
  expect_identical(evaluate_modal(modal_box(modal_bottom()),m,"b")$status,"ESTABLISHED")
  expect_identical(frame_check(m),list(reflexive=FALSE,irreflexive=TRUE,transitive=TRUE,acyclic=TRUE))
  reflexive<-kripke_model(list("a"),list(list("a","a")),list(p=list()))
  expect_identical(frame_check(reflexive),list(reflexive=TRUE,irreflexive=FALSE,transitive=TRUE,acyclic=FALSE))
  t<-modal_implication(modal_box(p),p)
  r<-validate_modal_frame(t,list("a"),list());expect_identical(r$status,"REFUTED")
  expect_identical(r$witness,list(world="a",valuation=list(p=list())))
  expect_identical(validate_modal_frame(t,list("a"),list(list("a","a")))$status,"ESTABLISHED")
  gl<-modal_implication(modal_box(modal_implication(modal_box(p),p)),modal_box(p))
  expect_identical(validate_modal_frame(gl,m$worlds,m$edges)$status,"ESTABLISHED")
  expect_identical(validate_modal_frame(gl,reflexive$worlds,reflexive$edges)$status,"REFUTED")
  expect_error(evaluate_modal(p,kripke_model(list("a"),list()),"a"),class="goedel_error")
  expect_error(validate_modal_frame(p,list("a","b"),list(),max_valuations=2),class="goedel_error")
  expect_error(evaluate_modal(modal_box(p),m,"a",max_steps=1),class="goedel_error")
  expect_error(kripke_model(list("a"),list(list("a","a"),list("a","a"))),class="goedel_error")
})
