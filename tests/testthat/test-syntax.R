test_that("constructors distinguish terms/formulas and enforce signature", {
  x <- variable("x"); z <- constant("zero")
  s <- function_term("s", list(x)); p <- predicate("P", list(s))
  expect_true(validate_expr(x)); expect_true(validate_expr(z)); expect_true(validate_expr(s))
  expect_true(validate_expr(equal(x, z)))
  expect_true(validate_expr(negate(p)))
  expect_true(validate_expr(conjunction(p, p)))
  expect_true(validate_expr(disjunction(p, p)))
  expect_true(validate_expr(implication(p, p)))
  expect_true(validate_expr(forall("x", p)))
  expect_true(validate_expr(exists_formula("x", p)))
  expect_true(validate_expr(bottom()))
  expect_error(negate(x), class = "goedel_error")
  expect_error(equal(p, x), class = "goedel_error")
  expect_error(variable("_x"), class = "goedel_error")
  expect_error(variable(NA_character_), class = "goedel_error")
  expect_error(variable(paste(rep("a", 65), collapse = "")), class = "goedel_error")
  expect_error(predicate("P", x), class = "goedel_error")
  expect_error(conjunction(predicate("P"), predicate("P", list(x))), class = "goedel_error")
})

test_that("capture avoidance handles shadowing and independent free variables", {
  f <- forall("y", conjunction(predicate("P", list(variable("x"), variable("y"))),
    forall("y", predicate("Q", list(variable("x"), variable("y"))))))
  g <- substitute_formula(f, "x", variable("y"))
  expect_identical(free_variables(f), "x")
  expect_identical(bound_variables(f), "y")
  expect_identical(free_variables(g), "y")
  expect_identical(bound_variables(g), c("v0", "v1"))
  expect_identical(serialize_record(substitute_formula(f, "y", variable("z"))), serialize_record(f))
  expect_true(alpha_equal(normalize(g), g))
  expect_identical(serialize_record(normalize(normalize(g))), serialize_record(normalize(g)))
})

test_that("JSON rejects duplicate and extra fields, malformed shapes and budgets", {
  expect_error(deserialize('{"args":[],"kind":"var","name":"x","name":"y"}'), class = "goedel_error")
  expect_error(deserialize('{"args":[],"kind":"var","name":"x","extra":1}'), class = "goedel_error")
  expect_error(deserialize('null'), class = "goedel_error")
  expect_error(deserialize('{"args":{},"kind":"var","name":"x"}'), class = "goedel_error")
  expect_error(deserialize(paste(rep(" ", 65537L), collapse = "")), class = "goedel_error")
  f <- predicate("P")
  for (i in seq_len(63L)) f <- negate(f)
  expect_error(negate(f), class = "goedel_error")
  expect_error(predicate("P", rep(list(variable("x")), 1000L)), class = "goedel_error")
  expect_output(print(variable("x")), "SYMBOLIC")
})

test_that("deterministic generated syntax satisfies independently stated invariants", {
  # Native generative properties: fixed seed, independently formulated FV law.
  set.seed(9142)
  for (i in seq_len(60L)) {
    names <- sample(c("x", "y", "z"), 3, replace = TRUE)
    f <- predicate("P", lapply(names, variable))
    binder <- sample(c("x", "y", "z"), 1)
    f <- forall(binder, f)
    expect_identical(free_variables(f), sort(setdiff(unique(names), binder)))
    replacement <- variable("w")
    g <- substitute_formula(f, "x", replacement)
    expected <- setdiff(free_variables(f), "x")
    if ("x" %in% free_variables(f)) expected <- union(expected, "w")
    expect_identical(free_variables(g), sort(expected))
    expect_identical(serialize_record(deserialize(serialize_record(g))), serialize_record(g))
    expect_identical(serialize_record(normalize(normalize(g))), serialize_record(normalize(g)))
  }
})
