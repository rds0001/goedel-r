test_that("a hypothetical representation cannot acquire reviewed status", {
  # This deliberately hypothetical graph is NOT a substitution representation.
  # Its explicit trusted premise permits checking only the logical bridge.
  phi<-list(schema_version="1.0",nodes=list(list(op="var",name="x0",args=list()),list(op="eq",name="",args=list(0L,0L))),root=1L)
  b<-goedel:::.dag_builder();vars<-lapply(0:3,function(i)b$node("var",paste0("x",i)))
  left<-b$node("eq",args=vars[1:2]);right<-b$node("eq",args=vars[3:4]);root<-b$node("and",args=list(left,right));graph<-b$export(root)
  program<-list(id="goedel-dag-closed-substitution-v1",version="test",register_count=4L,inputs=list(0L,1L,2L),output=3L,entry=0L,instructions=list(list(op="HALT")))
  hash<-goedel:::.register_hash(program);gh<-dag_fingerprint(graph)
  representation<-list(schema_version="1.0",program=program,representation=list(program_id=program$id,machine_id="goedel-arithmetic-register-v1",program_sha256=hash,arithmetic_dag=graph,bounded_dag=graph,arithmetic_sha256=gh,bounded_sha256=gh,inputs=list("x0","x1","x2"),output="x3"),review=list(status="INDEPENDENTLY_CHECKED",formal_kernel=FALSE,program_sha256=hash,arithmetic_sha256=gh,bounded_sha256=gh))
  result<-fixed_point(phi,representation)
  expect_identical(result$status,"UNKNOWN")
  expect_false(result$details$representation_reviewed)
  expect_true(result$details$code_equation_checked)
  expect_true(result$details$native_derivation_checked)
  expect_false(result$details$formal_kernel_replay)
  expect_false(result$assumptions[[1L]]$proved_by_native_checker)
  expect_length(result$witness$derivation,20L)
  checked<-check_scoped_dag_proof(result$witness$derivation,conclusion=result$witness$target)
  expect_identical(checked$status,"REFUTED")
  altered<-result$witness$derivation;altered[[16L]]$premises<-list(14L,10L)
  expect_identical(check_scoped_dag_proof(altered,axioms=result$witness$trusted_premises)$status,"REFUTED")
  expect_error(fixed_point(arithmetic_dag(parse_formula("0=0")),representation),class="goedel_error")
  representation$review$program_sha256<-strrep("0",64)
  expect_error(fixed_point(phi,representation),class="goedel_error")
})
