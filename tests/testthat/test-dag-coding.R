dag_node <- function(op,name="",args=list())list(op=op,name=name,args=args)
test_that("self-delimiting sequences match independent numeric oracle", {
  expect_identical(sequence_encode(list()),"1")
  for(pair in list(list("0","5"),list("1","19"),list("2","27")))expect_identical(sequence_encode(pair[1L]),pair[[2L]])
  expect_identical(sequence_encode(list("0","0")),"21")
  # For small codes, independent arithmetic formula, not the string implementation.
  cons<-function(a,s){v<-a+1;k<-floor(log2(v))+1;2^(2*k)*s+2^k-1+2^(k+1)*(v-2^(k-1))}
  for(a in 0:12)for(b in 0:8)expect_identical(sequence_encode(as.character(c(a,b))),as.character(cons(a,cons(b,1))))
  values<-list("0","1","1234567890123456789012345678901234567890")
  expect_identical(sequence_decode(sequence_encode(values)),values)
  for(code in c("0","2","3","4","6","7","01"))expect_error(sequence_decode(code),class="goedel_error")
  expect_error(sequence_encode(list("1"),max_bits=2L),class="goedel_error")
  expect_error(sequence_decode("21",max_items=1L),class="goedel_error")
  expect_identical(sequence_encode(list(),max_items=0L),"1")
  expect_identical(sequence_decode("1",max_items=0L),list())
  expect_error(sequence_encode(list("0"),max_items=0L),class="goedel_error")
  expect_error(sequence_decode("5",max_items=0L),class="goedel_error")
})
test_that("DAG presentation coding preserves nodes and exact variable identity", {
  d<-arithmetic_dag(parse_formula("x=x"))
  expect_identical(d$nodes[[1L]]$name,"x376")
  expect_identical(validate_arithmetic_dag(d),list(nodes=2L,root_sort="formula",expanded_nodes="3",free_variables=list("x376")))
  cells<-list("20261105","1","2","1","376","0","0","6","0","1","1")
  expect_identical(arithmetic_dag_encode(d),sequence_encode(cells))
  expect_identical(arithmetic_dag_decode(sequence_encode(cells)),d)
  changed<-dag_substitute_numeral(d,"x376","42")
  expect_length(changed$nodes,4L);expect_identical(changed$nodes[1:2],d$nodes)
  expect_identical(changed$nodes[[3L]],dag_node("num","42"))
  expect_identical(changed$nodes[[4L]]$args,list(2L,2L))
  expect_identical(validate_arithmetic_dag(changed)$free_variables,list())
  expect_identical(substitute_code(arithmetic_dag_encode(d),"376","42"),arithmetic_dag_encode(changed))
  expect_identical(substitute_code("0","0","0"),"0")
  bad<-cells;bad[[10L]]<-"2";expect_error(arithmetic_dag_decode(sequence_encode(bad)),class="goedel_error")
  expect_identical(substitute_code(sequence_encode(bad),"0","0"),"0")
  quant<-arithmetic_dag(parse_formula("forall x. x=x"));sub<-dag_substitute_numeral(quant,"x376","9")
  expect_identical(sub$nodes[[6L]]$args,quant$nodes[[3L]]$args)
  expect_identical(validate_arithmetic_dag(sub)$free_variables,list())
  duplicate<-d;duplicate$nodes<-c(d$nodes,list(d$nodes[[2L]]));duplicate$root<-2L
  expect_false(identical(arithmetic_dag_encode(duplicate),arithmetic_dag_encode(d)))
  expect_identical(validate_arithmetic_dag(duplicate)$expanded_nodes,"3")
})
test_that("general DAG substitution renames binders and respects shadows", {
  src<-list(schema_version="1.0",nodes=list(dag_node("var","x0"),dag_node("var","x1"),dag_node("eq",args=list(0L,1L)),dag_node("forall","x1",list(2L))),root=3L)
  term<-list(schema_version="1.0",nodes=list(dag_node("var","x1")),root=0L)
  result<-dag_substitute(src,"x0",term)
  expect_identical(validate_arithmetic_dag(result)$free_variables,list("x1"))
  expect_identical(tail(result$nodes,1L)[[1L]]$name,"x2")
  unchanged<-dag_substitute(src,"x1",term)
  expect_identical(validate_arithmetic_dag(unchanged)$free_variables,list("x0"))
  bad<-src;bad$nodes[[1L]]$args<-list(0L);expect_error(validate_arithmetic_dag(bad),class="goedel_error")
  bad<-src;bad$root<-0L;expect_error(validate_arithmetic_dag(bad),class="goedel_error")
  # Doubling a shared formula represents exponentially many expanded nodes.
  b<-list(schema_version="1.0",nodes=list(dag_node("bottom")),root=0L)
  for(i in 1:100)b$nodes[[i+1L]]<-dag_node("and",args=list(i-1L,i-1L))
  b$root<-100L
  expect_identical(validate_arithmetic_dag(b)$expanded_nodes,"2535301200456458802993406410751")
})
test_that("proof transport binds theory and does not confuse decoding with validity", {
  x<-variable("x");steps<-list(list(rule="eq_refl",formula=equal(x,x),premises=list(),scope=list()))
  record<-proof_object(steps,theory=arithmetic_theory("PA"))
  code<-encode_proof(record)
  expect_identical(decode_proof(code),record)
  expect_identical(check_proof_code(code,arithmetic_theory("PA"))$status,"ESTABLISHED")
  expect_error(check_proof_code(code,arithmetic_theory("Q")),class="goedel_error")
  bad<-record;bad$theory_sha256<-strrep("0",64);expect_error(encode_proof(bad),class="goedel_error")
  steps[[1L]]$formula<-equal(x,constant("a"))
  invalid<-proof_object(steps);expect_identical(check_proof_code(encode_proof(invalid))$status,"REFUTED")
  expect_error(decode_proof(sequence_encode(list("20261106","1","256"))),class="goedel_error")
})
test_that("DAG natural deduction checks scopes and eigenvariables without expansion", {
  f<-arithmetic_dag(parse_formula("x=x"));imp<-arithmetic_dag(parse_formula("(x=x) -> (x=x)"))
  steps<-list(list(rule="assume",formula=f,premises=list(),scope=list(1L)),list(rule="imp_intro",formula=imp,premises=list(1L),scope=list(),discharge=list(1L)))
  expect_identical(check_scoped_dag_proof(steps)$status,"ESTABLISHED")
  bad<-steps;bad[[2L]]$discharge<-list(2L);expect_identical(check_scoped_dag_proof(bad)$status,"REFUTED")
  b<-list(schema_version="1.0",nodes=list(dag_node("zero")),root=0L)
  for(i in 1:100)b$nodes[[i+1L]]<-dag_node("add",args=list(i-1L,i-1L))
  b$nodes[[102L]]<-dag_node("eq",args=list(100L,100L));b$root<-101L
  expect_identical(check_scoped_dag_proof(list(list(rule="eq_refl",formula=b,premises=list(),scope=list())))$status,"ESTABLISHED")
  universal<-arithmetic_dag(parse_formula("forall x. x=x"));term<-arithmetic_dag(numeral("2"));instance<-arithmetic_dag(parse_formula("2=2"))
  steps<-list(list(rule="axiom",formula=universal,premises=list(),scope=list()),list(rule="forall_elim",formula=instance,premises=list(1L),scope=list(),term=term))
  expect_identical(check_scoped_dag_proof(steps,axioms=list(universal))$status,"ESTABLISHED")
  steps<-list(list(rule="eq_refl",formula=f,premises=list(),scope=list()),list(rule="forall_intro",formula=universal,premises=list(1L),scope=list()))
  expect_identical(check_scoped_dag_proof(steps)$status,"ESTABLISHED")
  expect_identical(check_scoped_dag_proof(steps,assumptions=list(f))$status,"REFUTED")
  renamed<-arithmetic_dag(parse_formula("forall y. y=y"))
  steps<-list(list(rule="axiom",formula=renamed,premises=list(),scope=list()))
  expect_identical(check_scoped_dag_proof(steps,axioms=list(universal))$status,"ESTABLISHED")
  expect_error(check_scoped_dag_proof(list(list(rule="eq_refl",formula=term,premises=list(),scope=list()))),class="goedel_error")
})

test_that("bounded substitution keeps the binder fresh from the new bound", {
  nodes<-list(list(op="var",name="x0",args=list()),list(op="var",name="x1",args=list()),
    list(op="eq",name="",args=list(1L,1L)))
  term<-list(schema_version="1.0",nodes=list(nodes[[2L]]),root=0L)
  for(op in c("bforall","bexists")) {
    dag<-list(schema_version="1.0",nodes=c(nodes,list(list(op=op,name="x1",args=list(0L,2L)))),root=3L)
    out<-dag_substitute(dag,"x0",term)
    root<-out$nodes[[out$root+1L]]
    expect_identical(root$name,"x2")
    expect_identical(out$nodes[[root$args[[1L]]+1L]]$name,"x1")
    expect_identical(validate_arithmetic_dag(out,TRUE)$free_variables,list("x1"))
  }
})
