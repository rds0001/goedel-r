ndstep <- function(rule,formula,premises=list(),scope=list(),...)c(list(rule=rule,formula=formula,premises=premises,scope=scope),list(...))
test_that("scoped implication introduction discharges only live assumptions", {
  a<-predicate("A");b<-predicate("B")
  s<-list(ndstep("assume",a,scope=list(1L)),ndstep("imp_intro",implication(a,a),list(1L),discharge=list(1L)))
  r<-check_scoped_proof(s);expect_identical(r$status,"ESTABLISHED")
  expect_identical(r$dependencies,list(list(step=1L,local_assumptions=list(1L)),list(step=2L,local_assumptions=list())))
  expect_identical(r$details$steps_checked,2L)
  bad<-s;bad[[2L]]$formula<-implication(b,a);expect_identical(check_scoped_proof(bad)$status,"REFUTED")
  bad<-c(s,list(ndstep("reiterate",a,list(1L))));expect_identical(check_scoped_proof(bad)$status,"REFUTED")
  bad<-list(s[[1L]]);expect_identical(check_scoped_proof(bad)$details$reason,"UNCLOSED_SCOPE")
  bad<-s;bad[[2L]]$discharge<-list(2L);expect_identical(check_scoped_proof(bad)$status,"REFUTED")
  bad<-s;bad[[2L]]$extra<-TRUE;expect_error(check_scoped_proof(bad),class="goedel_error")
  bad<-s;bad[[2L]]$premises<-list(TRUE);expect_error(check_scoped_proof(bad),class="goedel_error")
})
test_that("propositional and classical rules validate hand deductions", {
  a<-predicate("A");b<-predicate("B");c<-predicate("C")
  assumptions<-list(disjunction(a,b),implication(a,c),implication(b,c))
  s<-lapply(assumptions,function(f)ndstep("assumption",f));s[[4L]]<-ndstep("or_elim",c,list(1L,2L,3L))
  expect_identical(check_scoped_proof(s,assumptions)$status,"ESTABLISHED")
  s[[4L]]$formula<-b;expect_identical(check_scoped_proof(s,assumptions)$status,"REFUTED")
  s<-list(ndstep("assume",negate(a),scope=list(1L)),ndstep("assumption",a,scope=list(1L)),
    ndstep("not_elim",bottom(),list(2L,1L),list(1L)),ndstep("classical",a,list(3L),discharge=list(1L)))
  expect_identical(check_scoped_proof(s,list(a))$status,"ESTABLISHED")
  expect_identical(check_scoped_proof(s,list(a),logic="intuitionistic")$status,"REFUTED")
  s[[4L]]<-ndstep("not_intro",negate(negate(a)),list(3L),discharge=list(1L))
  expect_identical(check_scoped_proof(s,list(a),logic="intuitionistic")$status,"ESTABLISHED")
  s<-list(ndstep("assumption",a),ndstep("or_left",disjunction(a,b),list(1L)),ndstep("or_right",disjunction(b,a),list(1L)),
    ndstep("and_intro",conjunction(a,a),list(1L,1L)),ndstep("and_left",a,list(4L)),ndstep("and_right",a,list(4L)))
  expect_identical(check_scoped_proof(s,list(a))$status,"ESTABLISHED")
  s<-list(ndstep("assumption",bottom()),ndstep("false_elim",a,list(1L)))
  expect_identical(check_scoped_proof(s,list(bottom()))$status,"ESTABLISHED")
})
test_that("equality elimination is capture avoiding and template controlled", {
  a<-constant("a");b<-constant("b");c<-constant("c");x<-variable("x")
  assumptions<-list(equal(a,b),equal(b,c),predicate("P",list(a)))
  s<-lapply(assumptions,function(f)ndstep("assumption",f))
  s[[4L]]<-ndstep("eq_trans",equal(a,c),list(1L,2L))
  s[[5L]]<-ndstep("eq_symm",equal(c,a),list(4L))
  s[[6L]]<-ndstep("eq_elim",predicate("P",list(b)),list(1L,3L),template=predicate("P",list(x)),variable="x")
  expect_identical(check_scoped_proof(s,assumptions)$status,"ESTABLISHED")
  s[[6L]]$formula<-predicate("P",list(c));expect_identical(check_scoped_proof(s,assumptions)$status,"REFUTED")
  s<-list(ndstep("eq_refl",equal(x,x)),ndstep("forall_intro",forall("x",equal(x,x)),list(1L)))
  expect_identical(check_scoped_proof(s)$status,"ESTABLISHED")
  expect_identical(check_scoped_proof(s,list(predicate("P",list(x))))$status,"REFUTED")
})
test_that("existential elimination cannot leak its eigenvariable", {
  x<-variable("x");a<-variable("a");p<-function(t)predicate("P",list(t))
  ex<-exists_formula("x",p(x));q<-predicate("Q");all<-forall("x",implication(p(x),q))
  s<-list(ndstep("assumption",ex),ndstep("assumption",all),ndstep("assume",p(a),scope=list(3L)),
    ndstep("forall_elim",implication(p(a),q),list(2L),list(3L),term=a),
    ndstep("mp",q,list(3L,4L),list(3L)),ndstep("exists_elim",q,list(1L,5L),discharge=list(3L),variable="a"))
  expect_identical(check_scoped_proof(s,list(ex,all))$status,"ESTABLISHED")
  expect_identical(check_scoped_proof(s,list(ex,all,p(a)))$status,"REFUTED")
  bad<-s;bad[[6L]]$formula<-p(a);bad[[6L]]$premises<-list(1L,3L);expect_identical(check_scoped_proof(bad,list(ex,all))$status,"REFUTED")
  intro<-list(ndstep("assumption",p(a)),ndstep("exists_intro",ex,list(1L),term=a))
  expect_identical(check_scoped_proof(intro,list(p(a)))$status,"ESTABLISHED")
  ax<-q_axioms()[[1L]];expect_identical(check_scoped_proof(list(ndstep("axiom",ax)),theory=arithmetic_theory("Q"))$status,"ESTABLISHED")
})

test_that("selected arithmetic theory fixes the joint symbol signature", {
  malformed<-function_term("S",list(variable("x"),variable("y")))
  steps<-list(ndstep("eq_refl",equal(malformed,malformed)))
  expect_identical(check_scoped_proof(steps)$status,"ESTABLISHED")
  expect_error(check_scoped_proof(steps,theory=arithmetic_theory("PA")),class="goedel_error")
  valid<-successor(variable("x"))
  expect_identical(check_scoped_proof(list(ndstep("eq_refl",equal(valid,valid))),theory=arithmetic_theory("PA"))$status,"ESTABLISHED")
})
