step <- function(rule, formula, premises = list(), ...) c(list(rule = rule, formula = formula, premises = premises), list(...))
test_that("finite rules check actual derivability and record trust", {
  a <- predicate("A"); b <- predicate("B")
  proof <- list(step("assumption", a), step("assumption", implication(a, b)), step("mp", b, list(1L, 2L)))
  result <- check_proof(proof, list(a, implication(a, b)), conclusion = b)
  expect_identical(result$status, "ESTABLISHED")
  expect_identical(result$mode, "CHECKED_DERIVATION")
  expect_length(result$evidence[[1]]$axioms, 0L)
  expect_output(print(result), "CHECKED_DERIVATION")
  proof[[3]]$formula <- a
  expect_identical(check_proof(proof, list(a, implication(a, b)))$status, "REFUTED")
  proof[[3]]$premises <- list(3L, 2L)
  expect_identical(check_proof(proof, list(a, implication(a, b)))$status, "REFUTED")
  proof[[3]]$premises <- list(TRUE, 2L)
  expect_error(check_proof(proof), class = "goedel_error")
  expect_identical(check_proof(list())$details$reason, "EMPTY_PROOF")
  expect_error(check_proof(list(step("invented", a))), class = "goedel_error")
  expect_error(check_proof(list(c(step("assumption", a), list(extra = 1)))), class = "goedel_error")
  expect_identical(check_proof(list(step("axiom", a)), axioms = list(a))$status, "ESTABLISHED")
  expect_identical(check_proof(list(step("axiom", a)), axioms = list(a), conclusion = b)$status, "REFUTED")
})

test_that("conjunction and quantifier rules enforce side conditions", {
  a <- predicate("A"); b <- predicate("B"); ab <- conjunction(a, b)
  proof <- list(step("assumption", a), step("assumption", b), step("and_intro", ab, list(1L, 2L)),
    step("and_left", a, list(3L)), step("and_right", b, list(3L)))
  expect_identical(check_proof(proof, list(a, b))$status, "ESTABLISHED")
  px <- predicate("P", list(variable("x"))); pz <- predicate("P", list(constant("z")))
  allp <- forall("x", px)
  expect_identical(check_proof(list(step("axiom", allp), step("forall_elim", pz, list(1L), term = constant("z"))), axioms = list(allp))$status, "ESTABLISHED")
  expect_error(check_proof(list(step("forall_elim", pz, list(1L)))), class = "goedel_error")
  expect_identical(check_proof(list(step("assumption", px), step("forall_intro", allp, list(1L))), list(px))$status, "REFUTED")
  expect_identical(check_proof(list(step("assumption", a), step("forall_intro", forall("x", a), list(1L))), list(a))$status, "ESTABLISHED")
  expect_error(check_proof(list(step("axiom", px)), axioms = list(px)), class = "goedel_error")
  expect_error(check_proof(list(step("assumption", predicate("P"))), list(px)), class = "goedel_error")
})

test_that("bounded search provides checked witnesses or explicit uncertainty", {
  a <- predicate("A"); b <- predicate("B")
  result <- bounded_proof_search(b, list(a, implication(a, b)))
  expect_identical(result$status, "ESTABLISHED")
  expect_identical(check_proof(result$witness, list(a, implication(a, b)))$status, "ESTABLISHED")
  expect_identical(bounded_proof_search(b, list(a, implication(a, b)), 2L)$details$termination_reason, "BOUND_EXHAUSTED")
  expect_identical(bounded_proof_search(b, list(a))$details$termination_reason, "SEARCH_SPACE_EXHAUSTED")
  expect_identical(bounded_proof_search(b, list(conjunction(a, b)))$status, "ESTABLISHED")
  expect_identical(bounded_proof_search(a, list(a), 1L)$status, "ESTABLISHED")
  expect_error(bounded_proof_search(a, max_steps = TRUE), class = "goedel_error")
  expect_error(bounded_proof_search(a, max_steps = 257L), class = "goedel_error")
  expect_error(bounded_proof_search(predicate("P"), list(predicate("P", list(variable("x"))))), class = "goedel_error")
})
